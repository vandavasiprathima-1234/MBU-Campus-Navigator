// Get all block names

export const blockNames = Object.keys(campusData);


// Get floors for selected block

export function getFloors(blockName) {

  if (!campusData[blockName]) {
    return [];
  }

  return Object.keys(campusData[blockName]);

}


// Get rooms for selected block + floor

export function getRooms(blockName, floorName) {

  if (!campusData[blockName]) {
    return {};
  }

  if (!campusData[blockName][floorName]) {
    return {};
  }

  return campusData[blockName][floorName];

}


// Get room details

export function getRoomDetails(
  blockName,
  floorName,
  roomNumber
) {

  return (
    campusData[blockName]?.[floorName]?.[roomNumber] ||
    null
  );

}


// Search room number

export function searchRoom(roomNumber) {

  const result = [];

  const search = String(roomNumber)
    .toLowerCase()
    .trim();

  for (const [block, floors] of Object.entries(campusData)) {

    for (const [floor, rooms] of Object.entries(floors)) {

      for (const [room, details] of Object.entries(rooms)) {

        if (
          room
            .toLowerCase()
            .includes(search)
        ) {

          result.push({

            block: block,

            floor: floor,

            room: room,

            details: details

          });

        }

      }

    }

  }

  return result;

}


// Search by room or detail

export function searchCampus(query) {

  const result = [];

  const search = String(query)
    .toLowerCase()
    .trim();

  for (const [block, floors] of Object.entries(campusData)) {

    for (const [floor, rooms] of Object.entries(floors)) {

      for (const [room, details] of Object.entries(rooms)) {

        if (

          block.toLowerCase().includes(search) ||

          floor.toLowerCase().includes(search) ||

          room.toLowerCase().includes(search) ||

          details.toLowerCase().includes(search)

        ) {

          result.push({

            block: block,

            floor: floor,

            room: room,

            details: details

          });

        }

      }

    }

  }

  return result;

}
